def outline(im: Image.Image, color: str = "outline") -> Image.Image:
    """Add a 1px 4-neighbour outline around opaque pixels."""
    out = im.copy()
    px, w, h = im.load(), im.width, im.height
    for y in range(h):
        for x in range(w):
            if px[x, y][3]:
                continue
            for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                nx, ny = x + dx, y + dy
                if 0 <= nx < w and 0 <= ny < h and px[nx, ny][3]:
                    out.putpixel((x, y), C[color] + (255,))
                    break
    return out


def relic() -> Image.Image:
    """The Sunstone: a golden disc with eight rays and a red-orange heart."""
    im = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    cx, cy = 7.5, 7.5
    for i in range(8):
        a = i * math.pi / 4
        x0, y0 = cx + math.cos(a) * 4.5, cy + math.sin(a) * 4.5
        x1, y1 = cx + math.cos(a) * 6.6, cy + math.sin(a) * 6.6
        d.line((x0, y0, x1, y1), fill=C["gold"] + (255,), width=1)
    d.ellipse((3, 3, 12, 12), fill=C["gold"] + (255,))
    d.ellipse((5, 5, 10, 10), fill=C["orange"] + (255,))
    d.ellipse((6, 6, 9, 9), fill=C["red"] + (255,))
    im.putpixel((5, 5), C["gold_light"] + (255,))
    im.putpixel((4, 6), C["gold_light"] + (255,))
    im.putpixel((6, 4), C["gold_light"] + (255,))
    return outline(im)


