def icon(size: int = 128) -> Image.Image:
    """Project icon: the hero on a teal medallion."""
    im = Image.new("RGBA", (32, 32), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    d.ellipse((0, 0, 31, 31), fill=C["outline"] + (255,))
    d.ellipse((1, 1, 30, 30), fill=C["gold"] + (255,))
    d.ellipse((3, 3, 28, 28), fill=C["teal_dark"] + (255,))
    im.alpha_composite(sword().rotate(-45, resample=Image.NEAREST), (13, 4))
    im.alpha_composite(grid(HERO_DOWN, HERO), (6, 9))
    return im.resize((size, size), Image.NEAREST)

