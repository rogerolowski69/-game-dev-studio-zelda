def gate() -> Image.Image:
    """A 32x16 locked iron gate set in a stone frame, with a gold padlock."""
    im = Image.new("RGBA", (32, 16), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    iron, iron_hi = C["ink"] + (255,), C["stone"] + (255,)
    for x in (4, 8, 12, 19, 23, 27):
        d.rectangle((x, 2, x + 1, 15), fill=iron)
        d.point((x, 3), fill=iron_hi)
    for y in (6, 12):
        d.rectangle((3, y, 28, y), fill=iron)
    # stone frame
    d.rectangle((0, 0, 31, 2), fill=C["stone"] + (255,))
    d.rectangle((0, 0, 31, 0), fill=C["stone_light"] + (255,))
    d.rectangle((0, 0, 2, 15), fill=C["stone"] + (255,))
    d.rectangle((29, 0, 31, 15), fill=C["stone"] + (255,))
    d.rectangle((0, 0, 0, 15), fill=C["stone_light"] + (255,))
    d.rectangle((31, 0, 31, 15), fill=C["stone_dark"] + (255,))
    # padlock
    d.rectangle((13, 4, 18, 5), outline=C["gold_dark"] + (255,))
    d.rectangle((12, 6, 19, 11), fill=C["gold"] + (255,), outline=C["outline"] + (255,))
    d.rectangle((15, 8, 16, 9), fill=C["outline"] + (255,))
    d.point((13, 7), fill=C["gold_light"] + (255,))
    return im


