def poof_sheet() -> Image.Image:
    """Three-frame smoke puff used for spawns, deaths and opened gates."""
    frames = []
    white, grey = C["white"] + (255,), C["stone_light"] + (255,)
    for i, r in enumerate((3, 5, 6)):
        im = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
        d = ImageDraw.Draw(im)
        if i == 0:
            d.ellipse((8 - r, 8 - r, 7 + r, 7 + r), fill=white)
        elif i == 1:
            for dx, dy in ((-3, -3), (3, -3), (-3, 3), (3, 3)):
                d.ellipse((8 + dx - 3, 8 + dy - 3, 7 + dx + 3, 7 + dy + 3), fill=grey)
                d.ellipse((8 + dx - 2, 8 + dy - 2, 7 + dx + 2, 7 + dy + 2), fill=white)
        else:
            for dx, dy in ((-5, -5), (5, -5), (-5, 5), (5, 5), (0, -6), (0, 6), (-6, 0), (6, 0)):
                d.ellipse((8 + dx - 1, 8 + dy - 1, 7 + dx + 1, 7 + dy + 1), fill=grey)
        frames.append(im)
    return sheet(frames, 3)


